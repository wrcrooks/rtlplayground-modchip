#!/usr/bin/env python3
"""Embed RTLPlayground's web UI and default config in the RP2350 firmware.

  embed_web.py OUT.c HTML_DIR CONFIG_TXT

Writes the files of HTML_DIR gzipped, with the same names and MIME types as
RTLPlayground's html_data.c, plus "/" for index.html, and config.txt as
rtl_default_config. The gzip header carries no timestamp, so the output only
changes when the inputs do.
"""
import gzip
import pathlib
import sys

MIME = {
    ".html": "text/html",
    ".ico": "image/svg+xml",  # RTLPlayground's favicon.ico is an SVG
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".js": "text/javascript",
    ".css": "text/css",
    ".txt": "text/plain",
}


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + "".join("0x%02x," % b for b in data[i:i + 16]))
    return "\n".join(lines)


def main():
    out, html_dir, config = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    files = sorted(p for p in html_dir.iterdir() if p.is_file() and p.suffix in MIME)
    src = ["// Generated by tools/embed_web.py, do not edit", "#include \"web_assets.h\"", ""]
    table = []
    for k, p in enumerate(files):
        data = gzip.compress(p.read_bytes(), compresslevel=9, mtime=0)
        src.append("static const uint8_t f%d[%d] = {\n%s\n};" % (k, len(data), c_bytes(data)))
        table.append((("/" + p.name), k, len(data), MIME[p.suffix]))
        if p.name == "index.html":
            table.append(("/", k, len(data), MIME[p.suffix]))
    src.append("")
    src.append("const struct web_asset web_assets[] = {")
    for name, k, n, mime in table:
        src.append('  { "%s", "%s", f%d, %d, 1 },' % (name, mime, k, n))
    src.append("  { 0 }")
    src.append("};")
    src.append("")
    text = config.read_text().replace("\\", "\\\\").replace('"', '\\"')
    src.append("const char rtl_default_config[] =")
    for line in text.splitlines(keepends=True):
        src.append('  "%s"' % line.replace("\n", "\\n"))
    src.append("  ;")
    new = "\n".join(src) + "\n"
    if not out.exists() or out.read_text() != new:
        out.write_text(new)


if __name__ == "__main__":
    main()
