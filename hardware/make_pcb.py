#!/usr/bin/env python3
"""Build modchip.kicad_pcb from the outline and header positions in outline.py.

Needs KiCad's Python API (pcbnew), so run it with KiCad's own Python. With
the KiCad 10 flatpak:

  flatpak run --command=python3 org.kicad.KiCad make_pcb.py

The board holds:
  Edge.Cuts   the outline from outline.py
  J1, J2, J3  the headers that mate with T3, T8 (2.0 mm) and T5 (2.54 mm),
              on the bottom side, pads checked against the switch's holes
  TP1         a through-hole pad above D3 for the reset wire to D3's anode
  Dwgs.User   the switch's PCB edge and the parts the outline avoids
  Cmts.User   U8's clip zone and notes
The headers and TP1 are linked to their symbols in modchip.kicad_sch
(make_sch.py), so Tools > Update PCB from Schematic adds the rest of the
parts around them.
The aux and grid origins are at T3 pin 1, the DXF's origin. Footprints come
from KiCad's standard library, so the file carries their current versions.
"""
import os, pathlib, sys
import pcbnew

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import outline as o  # noqa: E402
import kisexpr as k  # noqa: E402

OUT = HERE / "modchip.kicad_pcb"
OFFSET = (60.0, 40.0)           # switch coordinates -> sheet position (A4)
THICKNESS = 1.0                 # the stack in ARCHITECTURE.md assumes 1.0 mm
LAYERS = 4                      # for the RP2350's switching regulator
SHEET = k.uid("sheet/root")     # make_sch.py's root sheet


def lib_dir():
    for d in (os.environ.get("KICAD10_FOOTPRINT_DIR"), "/app/extensions/Library/footprints",
              "/usr/share/kicad/footprints"):
        if d and pathlib.Path(d, "Connector_PinHeader_2.00mm.pretty").is_dir():
            return pathlib.Path(d)
    sys.exit("KiCad footprint library not found; set KICAD10_FOOTPRINT_DIR")


def pt(p):
    return pcbnew.VECTOR2I_MM(p[0] + OFFSET[0], p[1] + OFFSET[1])


def shape(board, kind, layer, width=0.1):
    s = pcbnew.PCB_SHAPE(board)
    s.SetShape(kind)
    s.SetLayer(layer)
    s.SetWidth(pcbnew.FromMM(width))
    board.Add(s)
    return s


def text(board, s, p, layer, size=1.0):
    t = pcbnew.PCB_TEXT(board)
    t.SetText(s)
    t.SetPosition(pt(p))
    t.SetLayer(layer)
    t.SetTextSize(pcbnew.VECTOR2I_MM(size, size))
    t.SetTextThickness(pcbnew.FromMM(size * 0.15))
    board.Add(t)
    return t


def place(board, fp, targets, bottom):
    """Put fp so that pad n lands on targets[n-1], trying each orientation"""
    if bottom:
        fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_LEFT_RIGHT)
    want = [pt(t) for t in targets]
    for deg in (0, 90, 180, 270):
        fp.SetOrientationDegrees(deg)
        pads = {int(p.GetNumber()): p for p in fp.Pads()}
        fp.Move(want[0] - pads[1].GetPosition())
        if all((pads[n + 1].GetPosition() - w).EuclideanNorm() < pcbnew.FromMM(0.001)
               for n, w in enumerate(want)):
            return
    sys.exit("%s: no orientation puts its pads on the holes" % fp.GetReference())


def schematic_fields():
    """Reference -> {field: text} for the symbols in modchip.kicad_sch"""
    sch = HERE / "modchip.kicad_sch"
    if not sch.exists():
        return {}
    out = {}
    for sym in k.find(k.parse(sch.read_text()), "symbol"):
        props = {p[1]: p[2] for p in k.find(sym, "property")}
        if "Reference" in props:
            out[props["Reference"]] = props
    return out


SCH_FIELDS = schematic_fields()


def link(fp, lib, name):
    """Tie a footprint to its symbol in modchip.kicad_sch and take its fields,
    so that Update PCB from Schematic keeps it where it is and finds nothing
    to change"""
    ref = fp.GetReference()
    fp.SetPath(pcbnew.KIID_PATH("/%s/%s" % (SHEET, k.uid("sym/" + ref))))
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    fp.SetExcludedFromBOM(False)
    fields = SCH_FIELDS.get(ref, {})
    if "Value" in fields:
        fp.SetValue(fields["Value"])
    if "Description" in fields:
        fp.SetLibDescription(fields["Description"])
        f = fp.GetField(pcbnew.FIELD_T_DESCRIPTION) if hasattr(pcbnew, "FIELD_T_DESCRIPTION") else None
        if f:
            f.SetText(fields["Description"])


def main():
    lib = lib_dir()
    board = pcbnew.NewBoard(str(OUT))
    ds = board.GetDesignSettings()
    ds.SetBoardThickness(pcbnew.FromMM(THICKNESS))
    board.SetCopperLayerCount(LAYERS)
    ds.SetAuxOrigin(pt(o.T3[0]))
    ds.SetGridOrigin(pt(o.T3[0]))

    tb = board.GetTitleBlock()
    tb.SetTitle("RTLPlayground mod chip (RP2350), outline")
    tb.SetCompany("github.com/wrcrooks/RTLPlayground, modchip/")
    tb.SetRevision("A0")
    tb.SetComment(0, "For SWTG024AS-V2.0 (MokerLink 2G040210GS, XikeStor SKS3200M-4GPY2XF)")
    tb.SetComment(1, "Positions measured on a photo (+/-0.3 mm): check with calipers before ordering")
    tb.SetComment(2, "Generated by modchip/hardware/make_pcb.py from outline.py")

    # Outline
    pts = o.OUTLINE + o.OUTLINE[:1]
    for a, b in zip(pts, pts[1:]):
        s = shape(board, pcbnew.SHAPE_T_SEGMENT, pcbnew.Edge_Cuts, 0.05)
        s.SetStart(pt(a))
        s.SetEnd(pt(b))

    # Nets, by the switch header pin they reach
    nets = {}

    def net(name):
        if name not in nets:
            nets[name] = pcbnew.NETINFO_ITEM(board, name)
            board.Add(nets[name])
        return nets[name]

    headers = [
        ("J1", "To switch T3 (I2C slave)", "Connector_PinHeader_2.00mm", "PinHeader_1x06_P2.00mm_Vertical",
         o.T3, ["SW_SCL", "GND", "SW_SDA", "+3V3_SW", "SW_SPI_DO", "SW_SPI_CS"]),
        ("J2", "To switch T8 (GPIO46-49)", "Connector_PinHeader_2.00mm", "PinHeader_1x06_P2.00mm_Vertical",
         o.T8, ["SW_GPIO46", "GND", "SW_GPIO48", "+3V3_SW", "SW_GPIO47", "SW_GPIO49"]),
        ("J3", "To switch T5 (UART0)", "Connector_PinHeader_2.54mm", "PinHeader_1x04_P2.54mm_Vertical",
         o.T5, ["SW_U0TXD", "GND", "SW_U0RXD", None]),
    ]
    for ref, value, libname, name, holes, pins in headers:
        fp = pcbnew.FootprintLoad(str(lib / (libname + ".pretty")), name)
        fp.SetReference(ref)
        fp.SetValue(value)
        board.Add(fp)
        # Male pins point down into sockets on the switch: the header's
        # body sits under the board
        place(board, fp, holes, bottom=True)
        link(fp, libname, name)
        for p in fp.Pads():
            if pins[int(p.GetNumber()) - 1]:
                p.SetNet(net(pins[int(p.GetNumber()) - 1]))

    tp = pcbnew.FootprintLoad(str(lib / "TestPoint.pretty"), "TestPoint_THTPad_D1.5mm_Drill0.7mm")
    tp.SetReference("TP1")
    tp.SetValue("Reset: wire to D3 anode (front pad, + end)")
    board.Add(tp)
    place(board, tp, [o.RESET_PAD], bottom=False)
    link(tp, "TestPoint", "TestPoint_THTPad_D1.5mm_Drill0.7mm")
    next(iter(tp.Pads())).SetNet(net("SW_RESET_N"))

    # The switch underneath, for reference
    r = shape(board, pcbnew.SHAPE_T_RECTANGLE, pcbnew.Dwgs_User, 0.15)
    r.SetStart(pt((0, 0)))
    r.SetEnd(pt(o.BOARD))
    text(board, "SWTG024AS-V2.0 PCB edge (ports at the bottom)", (o.BOARD[0] / 2, o.BOARD[1] - 2),
         pcbnew.Dwgs_User, 1.5)
    for label, sh in o.OBSTACLES.items():
        if sh[0] == "rect":
            x0, y0, x1, y1 = sh[1:]
            s = shape(board, pcbnew.SHAPE_T_RECTANGLE, pcbnew.Dwgs_User)
            s.SetStart(pt((x0, max(y0, 0))))
            s.SetEnd(pt((x1, min(y1, o.BOARD[1]))))
            where = ((x0 + x1) / 2, (max(y0, 0) + min(y1, o.BOARD[1])) / 2)
        else:
            _, cx, cy, rad = sh
            s = shape(board, pcbnew.SHAPE_T_CIRCLE, pcbnew.Dwgs_User)
            s.SetCenter(pt((cx, cy)))
            s.SetEnd(pt((cx + rad, cy)))
            where = (cx, cy)
        text(board, label.split(" (")[0], where, pcbnew.Dwgs_User, 0.8)
    for label, sh in o.KEEPOUTS.items():
        s = shape(board, pcbnew.SHAPE_T_RECTANGLE, pcbnew.Cmts_User, 0.15)
        s.SetStart(pt(sh[1:3]))
        s.SetEnd(pt(sh[3:5]))
        text(board, label, ((sh[1] + sh[3]) / 2, sh[4] - 1.5), pcbnew.Cmts_User, 0.8)

    notes = [
        "Dwgs.User: the switch underneath. Cmts.User: keep U8 reachable for a clip.",
        "J1-J3 are male headers on the BOTTOM side; the switch gets low-profile sockets (about 4.5 mm).",
        "Keep the bottom side free of other parts: SMD parts on the switch sit up to 3 mm below it.",
        "Top-side parts: 3.2 mm at most, for about 8.7 mm above the switch PCB in all.",
        "Origin (aux, grid) at T3 pin 1. Positions +/-0.3 mm from a photo: verify before ordering.",
        "TP1: wire to D3's ANODE (front pad, by the +), never the banded end (3.3 V rail). 1 k in series in the driver.",
    ]
    for i, n in enumerate(notes):
        text(board, n, (o.BOARD[0] / 2, o.BOARD[1] + 6 + 2.2 * i), pcbnew.Cmts_User, 1.2)

    pcbnew.SaveBoard(str(OUT), board)
    print("wrote %s (KiCad %s)" % (OUT, pcbnew.Version()))


main()
